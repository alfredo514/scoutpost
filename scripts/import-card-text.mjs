#!/usr/bin/env node
/**
 * Turn data/card-text/*.json into SQL for the card_text table.
 *
 *   node scripts/import-card-text.mjs
 *   npx wrangler d1 execute scoutpost --remote --file=build/card-text.sql -y
 *
 * WHY THIS FILE EXISTS: the Riftscribe API publishes no rules text and no
 * flavor text. A card record carries id, public_code, name, set_id,
 * collector_number, variant, rarity, faction, domains, type, orientation,
 * stats and image URLs — and nothing else. The words printed on a card exist
 * only as pixels in the art, so they have to be transcribed by hand and stored
 * here.
 *
 * That makes this table deliberately sparse. A card with no row simply renders
 * without a text pane; the detail page never pretends to know something it
 * doesn't. Do not "fill in" text from memory — a wrong rules line on a site
 * people use to price decks is worse than a blank one.
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'data', 'card-text');
const OUT = join(ROOT, 'build', 'card-text.sql');

const s = (v) =>
  v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;
const n = (v) => (Number.isFinite(Number(v)) && v !== null && v !== '' ? String(Number(v)) : 'NULL');

const files = (await readdir(SRC)).filter((f) => f.endsWith('.json') && !f.startsWith('_'));
if (files.length === 0) {
  console.error(`No card text files in ${SRC}`);
  process.exit(1);
}

const sql = [
  '-- Generated by scripts/import-card-text.mjs — do not edit by hand.',
  `-- Generated ${new Date().toISOString()}`,
  '',
];

for (const file of files) {
  const c = JSON.parse(await readFile(join(SRC, file), 'utf8'));
  if (!c.card_id) {
    console.error(`${file}: missing card_id`);
    process.exit(1);
  }
  sql.push(
    `INSERT INTO card_text
       (card_id, energy_cost, power, subtitle, typeline, rules_text,
        reminder_text, flavor_text, artist, source, updated_at)
     VALUES (${s(c.card_id)}, ${n(c.energy_cost)}, ${n(c.power)}, ${s(c.subtitle)},
             ${s(c.typeline)}, ${s(c.rules_text)}, ${s(c.reminder_text)},
             ${s(c.flavor_text)}, ${s(c.artist)}, 'transcribed', datetime('now'))
     ON CONFLICT(card_id) DO UPDATE SET
       energy_cost=excluded.energy_cost, power=excluded.power,
       subtitle=excluded.subtitle, typeline=excluded.typeline,
       rules_text=excluded.rules_text, reminder_text=excluded.reminder_text,
       flavor_text=excluded.flavor_text, artist=excluded.artist,
       updated_at=datetime('now');`,
  );
  console.log(`  ${c.card_id}  ${c.name ?? ''}`);
}

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, `${sql.join('\n')}\n`, 'utf8');
console.log(`\n${files.length} card(s) → build/card-text.sql`);
